def _load_dotenv(path: Path) -> None:
    """Read .env into the environment, without adding a dependency.

    Existing environment variables always win, so a value set in the shell
    overrides the file. The file is gitignored: it is where the API key lives,
    and it is the only place it should live.
    """
    if not path.exists():
        return
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value


